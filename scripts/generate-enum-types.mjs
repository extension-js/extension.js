#!/usr/bin/env node

import {spawnSync} from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'
import {
  chromeTypesFile,
  comparable,
  stripComments
} from './generate-callback-types.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export const OUTPUT_FILE = path.join(
  ROOT,
  'programs',
  'extension',
  'types',
  'enums.d.ts'
)

// The enum objects a live Chrome has, read by scripts/capture-enum-objects.mjs.
// chrome-types alone cannot tell which of its unions the browser has one for.
export const DATA_FILE = path.join(ROOT, 'scripts', 'enum-objects.json')

// The key Chrome gives an enum value: upper case, with an underscore for a
// dash, between camel case words and before a leading digit.
export function enumKey(value) {
  let key = /^\d/.test(value) ? '_' : ''

  for (let index = 0; index < value.length; index++) {
    const char = value[index]

    if (index > 0 && /[a-z]/.test(value[index - 1]) && /[A-Z]/.test(char)) {
      key += `_${char}`
    } else if (char === '-') {
      key += '_'
    } else {
      key += char.toUpperCase()
    }
  }

  return key
}

// Every type that is a union of string literals alone, by its namespace path.
export function parseStringUnions(source) {
  const text = stripComments(source)
  const unions = new Map()
  const stack = []
  const pattern =
    /(?:declare\s+|export\s+)?namespace\s+([\w$.]+)\s*\{|export\s+type\s+([\w$]+)\s*=\s*(?:\|\s*)?("[^"]*"(?:\s*\|\s*"[^"]*")*)\s*;|\{|\}/g
  let match = pattern.exec(text)

  while (match) {
    if (match[1]) {
      stack.push(match[1])
    } else if (match[2]) {
      const namespace = stack.filter(Boolean).join('.')
      const values = Array.from(match[3].matchAll(/"([^"]*)"/g), (m) => m[1])

      if (!unions.has(`${namespace}.${match[2]}`)) {
        unions.set(`${namespace}.${match[2]}`, values)
      }
    } else if (match[0] === '{') {
      stack.push('')
    } else {
      stack.pop()
    }

    match = pattern.exec(text)
  }

  return unions
}

// An object for each union the browser was seen to have one for. The keys
// come from the values chrome-types declares, so the two cannot disagree.
export function enumObjects(source, captured) {
  const unions = parseStringUnions(source)
  const byNamespace = new Map()

  for (const name of Object.keys(captured.objects)) {
    const parts = name.split('.')
    const typeName = parts.pop()
    // chrome-types declares a reserved word with an underscore before it.
    const namespace = [parts.join('.'), `_${parts.join('.')}`]
      .map((candidate) => `browser.${candidate}`)
      .find((candidate) => unions.has(`${candidate}.${typeName}`))

    if (!namespace) continue

    const entries = new Map()

    for (const value of unions.get(`${namespace}.${typeName}`)) {
      const key = enumKey(value)

      if (key && !entries.has(key)) entries.set(key, value)
    }

    const objects = byNamespace.get(namespace) || []

    objects.push({name: typeName, entries: Array.from(entries)})
    byNamespace.set(namespace, objects)
  }

  return byNamespace
}

function renderKey(key) {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)
}

export function renderEnumTypes(source, captured) {
  const blocks = []

  for (const [namespace, objects] of enumObjects(source, captured)) {
    const body = objects
      .map(
        ({name, entries}) =>
          `  export const ${name}: {\n${entries
            .map(
              ([key, value]) =>
                `    readonly ${renderKey(key)}: ${JSON.stringify(value)}`
            )
            .join('\n')}\n  }`
      )
      .join('\n')

    blocks.push(`declare namespace ${namespace} {\n${body}\n}`)
  }

  return `// Generated by scripts/generate-enum-types.mjs from the chrome-types
// declarations and scripts/enum-objects.json. Do not edit: run the script
// again when chrome-types moves.
// Chrome has an object for each enum, like runtime.OnInstalledReason.INSTALL.
// chrome-types declares the values as a type and leaves the object out.
// The objects typed here are the ones read from ${captured.browser}.
/// <reference types="chrome-types" />

${blocks.join('\n\n')}
`
}

export function capturedEnumObjects() {
  return JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'))
}

function main() {
  const rendered = renderEnumTypes(
    fs.readFileSync(chromeTypesFile(), 'utf8'),
    capturedEnumObjects()
  )

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT_FILE)
      ? fs.readFileSync(OUTPUT_FILE, 'utf8')
      : ''

    if (comparable(current) !== comparable(rendered)) {
      console.error(
        `${path.relative(ROOT, OUTPUT_FILE)} is behind chrome-types. Run node scripts/generate-enum-types.mjs`
      )

      process.exit(1)
    }

    return
  }

  fs.writeFileSync(OUTPUT_FILE, rendered)

  const formatted = spawnSync(
    path.join(ROOT, 'node_modules', '.bin', 'biome'),
    ['format', '--write', OUTPUT_FILE],
    {cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32'}
  )

  process.exit(formatted.status ?? 1)
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main()
}
