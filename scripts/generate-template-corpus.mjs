#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PIN_FILE = path.join(
  ROOT,
  'programs/create/steps/import-external-template.ts'
)
const OUT_FILE = path.join(
  ROOT,
  'programs/extension/helpers/template-corpus.generated.ts'
)

const CORPUS_REPO = 'extension-js/examples'
const CORPUS_BRANCH = 'main'
const PIN_PATTERN = /export const DEFAULT_TEMPLATES_REF = '([0-9a-f]{40})'/

const BANNER = [
  '//  ██████╗██╗     ██╗',
  '// ██╔════╝██║     ██║',
  '// ██║     ██║     ██║',
  '// ██║     ██║     ██║',
  '// ╚██████╗███████╗██║',
  '//  ╚═════╝╚══════╝╚═╝',
  '// MIT License (c) 2020–present Cezar Augusto & the Extension.js authors, presence implies inheritance'
].join('\n')

export function readPinnedRef(source) {
  const match = PIN_PATTERN.exec(source)

  if (!match) {
    throw new Error(
      `Could not read DEFAULT_TEMPLATES_REF from ${path.relative(ROOT, PIN_FILE)}`
    )
  }

  return match[1]
}

export function writePinnedRef(source, ref) {
  if (!PIN_PATTERN.test(source)) {
    throw new Error('Refusing to move a pin this file does not declare')
  }

  return source.replace(
    PIN_PATTERN,
    `export const DEFAULT_TEMPLATES_REF = '${ref}'`
  )
}

export function renderCorpusModule({repo, ref, slugs}) {
  return [
    BANNER,
    '',
    '// GENERATED by scripts/generate-template-corpus.mjs. Do not edit by hand.',
    '// These are the folders extension-js/examples publishes under examples/ at',
    '// the exact commit extension-create downloads from, so the names the CLI',
    '// advertises and the names it can scaffold are one list.',
    '',
    `export const TEMPLATE_CORPUS_REPO = '${repo}'`,
    '',
    `export const TEMPLATE_CORPUS_REF = '${ref}'`,
    '',
    'export const TEMPLATE_CORPUS_SLUGS: readonly string[] = [',
    // No trailing comma on the last entry: the repo formatter strips it, and a
    // generator whose output the formatter rewrites reports drift forever.
    slugs.map((slug) => `  '${slug}'`).join(',\n'),
    ']',
    ''
  ].join('\n')
}

async function githubJson(url) {
  const headers = {
    'User-Agent': 'extension-template-corpus-generator',
    Accept: 'application/vnd.github+json'
  }

  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`
  }

  const response = await fetch(url, {headers})
  const body = await response.json()

  if (!response.ok) {
    throw new Error(
      `GitHub said ${response.status} for ${url}: ${body?.message || ''}`
    )
  }

  return body
}

// A pin only buys reproducibility while the commit stays reachable. The CLI
// shipped for two weeks pinned to a bot commit that no branch or tag contained,
// which GitHub still served but never promised to keep. Refuse that shape.
async function assertRefIsReachable(ref) {
  const url = `https://api.github.com/repos/${CORPUS_REPO}/compare/${CORPUS_BRANCH}...${ref}`
  const headers = {
    'User-Agent': 'extension-template-corpus-generator',
    Accept: 'application/vnd.github+json'
  }

  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`
  }

  const response = await fetch(url, {headers})

  if (response.status === 404) {
    throw new Error(
      `${ref} shares no ancestor with ${CORPUS_REPO}@${CORPUS_BRANCH}. ` +
        'An unreachable commit can be collected at any time and every ' +
        'non-bundled create would break at once. Pin a commit on the branch.'
    )
  }

  const body = await response.json()

  if (!response.ok) {
    throw new Error(
      `GitHub said ${response.status} comparing ${ref}: ${body?.message || ''}`
    )
  }

  if (body.status !== 'behind' && body.status !== 'identical') {
    throw new Error(
      `${ref} is ${body.status} relative to ${CORPUS_BRANCH}, not an ancestor of it.`
    )
  }
}

async function fetchCorpusSlugs(ref) {
  const entries = await githubJson(
    `https://api.github.com/repos/${CORPUS_REPO}/contents/examples?ref=${ref}`
  )

  if (!Array.isArray(entries)) {
    throw new Error(`Unexpected contents payload for ${ref}`)
  }

  const slugs = entries
    .filter((entry) => entry.type === 'dir')
    .map((entry) => entry.name)
    .sort()
  if (!slugs.length) throw new Error(`No template folders found at ${ref}`)

  return slugs
}

// The release job repins to the corpus head, so `--ref main` resolves the
// branch to the commit it points at right now. Only the branch name is
// accepted, a tag or a short sha would pin something this script cannot
// prove reachable the same way.
async function resolveBranchHead(branch) {
  const body = await githubJson(
    `https://api.github.com/repos/${CORPUS_REPO}/commits/${branch}`
  )
  const sha = String(body?.sha || '').toLowerCase()

  if (!/^[0-9a-f]{40}$/.test(sha)) {
    throw new Error(`Could not resolve ${CORPUS_REPO}@${branch} to a commit`)
  }

  return sha
}

export function parseRequestedRef(value) {
  if (value === undefined) return undefined

  const ref = String(value).toLowerCase()
  if (ref === CORPUS_BRANCH) return ref
  if (/^[0-9a-f]{40}$/.test(ref)) return ref

  throw new Error(
    `--ref takes a full 40-character commit SHA or ${CORPUS_BRANCH}`
  )
}

async function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const refFlagIndex = args.indexOf('--ref')
  const requestedRef = parseRequestedRef(
    refFlagIndex === -1 ? undefined : args[refFlagIndex + 1]
  )

  const pinSource = fs.readFileSync(PIN_FILE, 'utf8')
  const ref =
    requestedRef === CORPUS_BRANCH
      ? await resolveBranchHead(CORPUS_BRANCH)
      : requestedRef || readPinnedRef(pinSource)

  await assertRefIsReachable(ref)
  const slugs = await fetchCorpusSlugs(ref)
  const next = renderCorpusModule({repo: CORPUS_REPO, ref, slugs})
  const current = fs.existsSync(OUT_FILE)
    ? fs.readFileSync(OUT_FILE, 'utf8')
    : ''

  if (check) {
    if (current !== next) {
      console.error(
        `${path.relative(ROOT, OUT_FILE)} is stale for ${CORPUS_REPO}@${ref}.\n` +
          'Run: node scripts/generate-template-corpus.mjs'
      )

      process.exit(1)
    }

    if (readPinnedRef(pinSource) !== ref) {
      console.error('The scaffolder pin and the generated corpus disagree.')
      process.exit(1)
    }

    console.log(`Template corpus is current at ${ref} (${slugs.length} names).`)

    return
  }

  if (current !== next) fs.writeFileSync(OUT_FILE, next)

  if (readPinnedRef(pinSource) !== ref) {
    fs.writeFileSync(PIN_FILE, writePinnedRef(pinSource, ref))
  }

  console.log(
    `Wrote ${slugs.length} template names from ${CORPUS_REPO}@${ref}.`
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
