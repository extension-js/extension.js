import type {Manifest} from '../../../../types'

// Declaring externally_connectable without ids closes the extension to every
// other extension, so dev reopens it. A declared allowlist is the author's call.
export default function patchExternallyConnectable(manifest: Manifest) {
  if (manifest.externally_connectable && !manifest.externally_connectable.ids) {
    return {
      externally_connectable: {
        ...manifest.externally_connectable,
        ids: ['*']
      }
    }
  }

  return {}
}
