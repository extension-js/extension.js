import {type ErrorCode} from './messaging'

export interface CodedError extends Error {
  code: ErrorCode
}

// A refusal the CLI reports as one envelope: the prose stays the human line and
// the code is the part a machine consumer matches on.
export function codedError(code: ErrorCode, message: string): CodedError {
  const error = new Error(message) as CodedError
  error.code = code

  return error
}
