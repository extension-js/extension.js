import {hasDependency} from './has-dependency'

// Whether a project depends on a framework that brings its own refresh
// runtime. Read from the project's package.json, with no notice attached.
export function usesReact(projectPath: string): boolean {
  return hasDependency(projectPath, 'react')
}

export function usesVue(projectPath: string): boolean {
  return hasDependency(projectPath, 'vue')
}

export function usesSvelte(projectPath: string): boolean {
  return hasDependency(projectPath, 'svelte')
}
