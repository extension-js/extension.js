export const HOT_UPDATES_FOLDER = 'hot'

// A dev session writes hot updates under this folder with no `.hot-update`
// infix, and a compile without its renaming keeps the infix. Anchored, so a
// user page under its own folder of that name keeps its chunk.
export function isHotUpdateFile(file: string): boolean {
  return (
    file.toLowerCase().startsWith(`${HOT_UPDATES_FOLDER}/`) ||
    /\.hot-update\./i.test(file)
  )
}
