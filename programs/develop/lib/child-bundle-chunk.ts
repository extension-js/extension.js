// A child compilation's chunk under these folders holds sources the reload
// classifier reads from it. A child's chunk under another name is not read.
const CHILD_BUNDLE_CHUNK = /^(?:scripts|content_scripts)\//

export function isChildBundleChunkName(name: string): boolean {
  return CHILD_BUNDLE_CHUNK.test(name)
}
