export type Notice = {delivered: boolean}

// One record per line a build prints once. The plugin holds one set for the
// compiler it is applied to, so a second build in the process prints its own.
export interface SessionNotices {
  react: Notice
  preact: Notice
  vue: Notice
  solid: Notice
  svelte: Notice
  svelteMismatch: Notice
  customLoader: Notice
  typescript: Notice
}

export function createSessionNotices(): SessionNotices {
  return {
    react: {delivered: false},
    preact: {delivered: false},
    vue: {delivered: false},
    solid: {delivered: false},
    svelte: {delivered: false},
    svelteMismatch: {delivered: false},
    customLoader: {delivered: false},
    typescript: {delivered: false}
  }
}
