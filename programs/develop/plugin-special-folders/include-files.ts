import * as fs from 'node:fs'
import * as path from 'node:path'
import {type Compilation, type Compiler, rspack} from '@rspack/core'
import type {IncludeFilesConfig} from '../types'
import * as messages from './messages'

export interface IncludeFilesOptions {
  include: IncludeFilesConfig | undefined
  projectRoot: string
}

type Verdict =
  | {kind: 'ok'; output: string; source: string; isDir: boolean}
  | {kind: 'invalid'; output: string; reason: string}
  | {kind: 'missing'; output: string; source: string}

function judgeOutputPath(output: string): string | undefined {
  const trimmed = String(output || '').trim()
  if (trimmed === '') return 'the output path is empty'

  if (path.isAbsolute(trimmed) || /^[a-z]:[\\/]/i.test(trimmed)) {
    return 'the output path is absolute, and it has to be relative to the extension root'
  }

  const segments = trimmed.split(/[\\/]+/)

  if (segments.includes('..')) {
    return 'the output path climbs out of the extension root'
  }

  if (segments.join('/') === 'manifest.json') {
    return 'manifest.json is generated by the build and cannot be replaced'
  }

  return undefined
}

export function judgeIncludeFiles(
  include: IncludeFilesConfig | undefined,
  projectRoot: string
): Verdict[] {
  const verdicts: Verdict[] = []

  for (const [output, source] of Object.entries(include || {})) {
    const reason = judgeOutputPath(output)

    if (reason) {
      verdicts.push({kind: 'invalid', output, reason})
      continue
    }

    if (typeof source !== 'string' || source.trim() === '') {
      verdicts.push({
        kind: 'invalid',
        output,
        reason: 'the source path has to be a non-empty string'
      })

      continue
    }

    const abs = path.resolve(projectRoot, source)
    let isDir = false

    try {
      isDir = fs.statSync(abs).isDirectory()
    } catch {
      verdicts.push({kind: 'missing', output, source: abs})
      continue
    }

    verdicts.push({
      kind: 'ok',
      output: output
        .trim()
        .split(/[\\/]+/)
        .join('/'),
      source: abs,
      isDir
    })
  }

  return verdicts
}

// Copies the files `include` declares into the output, the way public/ is
// copied: the bundler watches each source, so an edit lands on the next
// compile without a restart.
export class IncludeFiles {
  public static readonly name: string = 'plugin-special-folders:include'

  private readonly options: IncludeFilesOptions

  constructor(options: IncludeFilesOptions) {
    this.options = options
  }

  apply(compiler: Compiler) {
    const {include, projectRoot} = this.options
    if (!include || Object.keys(include).length === 0) return

    const verdicts = judgeIncludeFiles(include, projectRoot)
    const copies = verdicts.filter((v) => v.kind === 'ok')

    if (copies.length > 0) {
      new rspack.CopyRspackPlugin({
        patterns: copies.map((copy) => ({
          from: copy.source,
          to: copy.output,
          toType: copy.isDir ? ('dir' as const) : ('file' as const),
          // A source that vanishes mid-session is reported below, once per
          // compile, in words that name the config key.
          noErrorOnMissing: true
        }))
      }).apply(compiler)
    }

    compiler.hooks.thisCompilation.tap(
      IncludeFiles.name,
      (compilation: Compilation) => {
        const ErrorCtor = compiler.rspack?.WebpackError || Error

        // Re-judge per compile: a file that appeared or vanished since the
        // session started changes the verdict, and the copier is silent on it.
        for (const verdict of judgeIncludeFiles(include, projectRoot)) {
          if (verdict.kind === 'ok') {
            compilation.fileDependencies?.add(verdict.source)
            continue
          }

          const error = new ErrorCtor(
            verdict.kind === 'missing'
              ? messages.includeSourceMissing(
                  verdict.output,
                  verdict.source,
                  projectRoot
                )
              : messages.includeOutputPathInvalid(
                  verdict.output,
                  verdict.reason
                )
          )
          error.name = 'IncludeFilesError'
          compilation.errors.push(error)
        }
      }
    )
  }
}
