import * as fs from 'node:fs'
import * as path from 'node:path'
import {type Compilation, type Compiler, rspack} from '@rspack/core'
import type {IncludeFilesConfig} from '../types'
import * as messages from './messages'

export interface IncludeFilesOptions {
  include: IncludeFilesConfig | undefined
  projectRoot: string
}

type Verdict =
  | {
      kind: 'ok'
      output: string
      source: string
      isDir: boolean
      minify: boolean
    }
  | {kind: 'invalid'; output: string; reason: string}
  | {kind: 'missing'; output: string; source: string}

function judgeOutputPath(output: string): string | undefined {
  const trimmed = String(output || '').trim()
  if (trimmed === '') return 'the output path is empty'

  if (path.isAbsolute(trimmed) || /^[a-z]:[\\/]/i.test(trimmed)) {
    return 'the output path is absolute, and it has to be relative to the extension root'
  }

  const segments = trimmed.split(/[\\/]+/)

  if (segments.includes('..')) {
    return 'the output path climbs out of the extension root'
  }

  if (segments.join('/') === 'manifest.json') {
    return 'manifest.json is generated by the build and cannot be replaced'
  }

  return undefined
}

// A .min.js is minified already, and a second pass only costs it the
// comment that names its source map.
const SCRIPT_FILE = /(?<!\.min)\.(?:js|mjs|cjs)$/i

// An entry is a source path, or {from, minify} to keep a script as authored.
function readIncludeEntry(
  entry: unknown
): {from: string; minify: boolean} | string {
  if (typeof entry === 'string') {
    return entry.trim() === ''
      ? 'the source path has to be a non-empty string'
      : {from: entry, minify: true}
  }

  if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
    return 'the source has to be a path, or an object such as {from: "vendor/lib.js", minify: false}'
  }

  const {from, minify, ...rest} = entry as Record<string, unknown>

  if (typeof from !== 'string' || from.trim() === '') {
    return 'from has to be a non-empty source path'
  }

  if (minify !== undefined && typeof minify !== 'boolean') {
    return 'minify has to be true or false'
  }

  const unknown = Object.keys(rest)

  if (unknown.length > 0) {
    return `${unknown.join(', ')} is not a key an entry reads, which are from and minify`
  }

  return {from, minify: minify !== false}
}

// Names are shortened and comments dropped, and no statement is rewritten,
// so the value executeScript reads off the last one stays. Banners stay too.
export async function minifyIncludedScript(
  input: Buffer,
  absoluteFilename: string
): Promise<Buffer> {
  try {
    const {code} = await rspack.experiments.swc.minify(input.toString('utf8'), {
      compress: false,
      mangle: true,
      format: {comments: 'some'},
      ...(/\.mjs$/i.test(absoluteFilename) ? {module: true} : {})
    })

    return Buffer.from(code)
  } catch {
    // A file the minifier cannot parse ships as authored.
    return input
  }
}

export function judgeIncludeFiles(
  include: IncludeFilesConfig | undefined,
  projectRoot: string
): Verdict[] {
  const verdicts: Verdict[] = []

  for (const [output, entry] of Object.entries(include || {})) {
    const reason = judgeOutputPath(output)

    if (reason) {
      verdicts.push({kind: 'invalid', output, reason})
      continue
    }

    const read = readIncludeEntry(entry)

    if (typeof read === 'string') {
      verdicts.push({kind: 'invalid', output, reason: read})
      continue
    }

    const abs = path.resolve(projectRoot, read.from)
    let isDir = false

    try {
      isDir = fs.statSync(abs).isDirectory()
    } catch {
      verdicts.push({kind: 'missing', output, source: abs})
      continue
    }

    verdicts.push({
      kind: 'ok',
      output: output
        .trim()
        .split(/[\\/]+/)
        .join('/'),
      source: abs,
      isDir,
      minify: read.minify
    })
  }

  return verdicts
}

// Copies the files `include` declares into the output, the way public/ is
// copied: the bundler watches each source, so an edit lands on the next
// compile without a restart.
export class IncludeFiles {
  public static readonly name: string = 'plugin-special-folders:include'

  private readonly options: IncludeFilesOptions

  constructor(options: IncludeFilesOptions) {
    this.options = options
  }

  apply(compiler: Compiler) {
    const {include, projectRoot} = this.options
    if (!include || Object.keys(include).length === 0) return

    const verdicts = judgeIncludeFiles(include, projectRoot)
    const copies = verdicts.filter((v) => v.kind === 'ok')

    if (copies.length > 0) {
      new rspack.CopyRspackPlugin({
        patterns: copies.map((copy) => ({
          from: copy.source,
          to: copy.output,
          toType: copy.isDir ? ('dir' as const) : ('file' as const),
          // A source that vanishes mid-session is reported below, once per
          // compile, in words that name the config key.
          noErrorOnMissing: true,
          // The build's own minimizers leave a declared file alone. A script
          // gets the pass below, which keeps the value it ends on.
          info: {minimized: true},
          ...(copy.minify
            ? {
                transform: (input: Buffer, absoluteFilename: string) =>
                  SCRIPT_FILE.test(absoluteFilename) &&
                  compiler.options.optimization?.minimize === true
                    ? minifyIncludedScript(input, absoluteFilename)
                    : input
              }
            : {})
        }))
      }).apply(compiler)
    }

    compiler.hooks.thisCompilation.tap(
      IncludeFiles.name,
      (compilation: Compilation) => {
        const ErrorCtor = compiler.rspack?.WebpackError || Error

        // Re-judge per compile: a file that appeared or vanished since the
        // session started changes the verdict, and the copier is silent on it.
        for (const verdict of judgeIncludeFiles(include, projectRoot)) {
          if (verdict.kind === 'ok') {
            compilation.fileDependencies?.add(verdict.source)
            continue
          }

          const error = new ErrorCtor(
            verdict.kind === 'missing'
              ? messages.includeSourceMissing(
                  verdict.output,
                  verdict.source,
                  projectRoot
                )
              : messages.includeOutputPathInvalid(
                  verdict.output,
                  verdict.reason
                )
          )
          error.name = 'IncludeFilesError'
          compilation.errors.push(error)
        }
      }
    )
  }
}
